-- ESPACE ENTREPRISES, PREUVES DE PARTAGE ET VISIONNAGES SPONSORISES
-- Les paiements MVola et les validations sont MANUELS dans cette version.
-- Les récompenses sont créditées seulement après validation depuis Supabase.

create table if not exists public.ad_campaigns (
  id bigint generated by default as identity primary key,
  company_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  description text not null,
  campaign_type text not null check (campaign_type in ('promotion','video')),
  video_url text,
  budget_ariary bigint not null check (budget_ariary >= 1000),
  reward_ariary bigint not null check (reward_ariary >= 50),
  payment_reference text not null unique,
  payment_proof_path text not null,
  status text not null default 'pending_review' check (status in ('pending_review','active','rejected','finished')),
  created_at timestamptz not null default now(),
  constraint video_campaign_requires_url check (campaign_type <> 'video' or video_url is not null)
);

create table if not exists public.promotion_proofs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  social_network text not null,
  proof_path text not null,
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  reward_ariary bigint not null default 100 check (reward_ariary >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.video_views (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  campaign_id bigint not null references public.ad_campaigns(id) on delete cascade,
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  created_at timestamptz not null default now(),
  unique(user_id,campaign_id)
);

