create or replace function public.check_video_campaign_budget()
returns trigger language plpgsql security definer set search_path = public as $$
declare v_budget bigint; v_reward bigint; v_used bigint;
begin
  select budget_ariary,reward_ariary into v_budget,v_reward
  from public.ad_campaigns where id = new.campaign_id and status = 'active' and campaign_type = 'video';
  if v_budget is null then raise exception 'Cette campagne vidéo n’est pas active.'; end if;
  select count(*) * v_reward into v_used from public.video_views where campaign_id = new.campaign_id and status in ('pending','approved');
  if v_used + v_reward > v_budget then raise exception 'Le budget de cette campagne est épuisé.'; end if;
  return new;
end; $$;
drop trigger if exists trg_check_video_campaign_budget on public.video_views;
create trigger trg_check_video_campaign_budget before insert on public.video_views
for each row execute function public.check_video_campaign_budget();
