-- Les récompenses restent en attente. Un administrateur change le statut à 'approved'
-- dans Table Editor ; le déclencheur crédite alors le portefeuille une seule fois.
create or replace function public.credit_approved_promotion()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.status = 'approved' and old.status <> 'approved' then
    update public.profiles set balance = balance + new.reward_ariary where id = new.user_id;
    insert into public.wallet_transactions(user_id,description,amount)
    values(new.user_id,'Partage MADA JOBS validé',new.reward_ariary);
  end if;
  return new;
end; $$;
drop trigger if exists trg_credit_approved_promotion on public.promotion_proofs;
create trigger trg_credit_approved_promotion after update of status on public.promotion_proofs
for each row execute function public.credit_approved_promotion();

create or replace function public.credit_approved_video_view()
returns trigger language plpgsql security definer set search_path = public as $$
declare v_reward bigint; v_title text;
begin
  if new.status = 'approved' and old.status <> 'approved' then
    select reward_ariary,title into v_reward,v_title from public.ad_campaigns where id = new.campaign_id;
    update public.profiles set balance = balance + v_reward where id = new.user_id;
    insert into public.wallet_transactions(user_id,description,amount)
    values(new.user_id,'Vidéo sponsorisée : ' || coalesce(v_title,'Campagne'),v_reward);
  end if;
  return new;
end; $$;
drop trigger if exists trg_credit_approved_video_view on public.video_views;
create trigger trg_credit_approved_video_view after update of status on public.video_views
for each row execute function public.credit_approved_video_view();

